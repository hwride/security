import { existsSync } from "node:fs";
import { execFile as execFileCallback } from "node:child_process";
import { platform } from "node:os";
import { resolve } from "node:path";
import { promisify } from "node:util";
import {
  getDefaultBuildCaPath,
  getLoginKeychainPath,
  getRootCaCertPath,
} from "./util/paths.ts";

/*
  Will remove the root certificate authority certificate generated by the
  generate-ca.ts script from the system trust store.

  Supports the macOS login keychain and Windows current-user Trusted Root store.
 */

const execFile = promisify(execFileCallback);

const defaultRootCaCertPath = getRootCaCertPath(getDefaultBuildCaPath());
const loginKeychainPath = getLoginKeychainPath();

if (import.meta.main) {
  uninstallCa().catch(handleFatalError);
}

export async function uninstallCa(certificatePath = defaultRootCaCertPath) {
  const resolvedCertificatePath = resolve(certificatePath);

  if (platform() !== "darwin" && platform() !== "win32") {
    throw new Error(
      `uninstall-ca.ts only supports macOS (darwin) and Windows (win32). Current platform is ${platform()}.`,
    );
  }

  if (!existsSync(resolvedCertificatePath)) {
    throw new Error(
      `Root CA certificate not found at ${resolvedCertificatePath}. Run generate-ca.ts first to create build-ca output.`,
    );
  }

  console.log(
    platform() === "win32"
      ? "Deleting root CA certificate from Windows current-user Trusted Root store."
      : `Deleting root CA certificate from login keychain: ${loginKeychainPath}`,
  );
  const certificateFingerprint = await getCertificateFingerprint(
    resolvedCertificatePath,
    platform() === "win32" ? "sha1" : "sha256",
  );
  if (platform() === "win32") {
    await execFile("certutil.exe", [
      "-user",
      "-delstore",
      "Root",
      certificateFingerprint,
    ]);
  } else {
    await execFile("security", [
      "delete-certificate",
      "-Z",
      certificateFingerprint,
      "-t",
      loginKeychainPath,
    ]);
  }

  console.log("Root CA certificate removed successfully.");
}

async function getCertificateFingerprint(
  certificatePath: string,
  algorithm: "sha1" | "sha256",
) {
  const { stdout } = await execFile("openssl", [
    "x509",
    "-in",
    certificatePath,
    "-noout",
    "-fingerprint",
    `-${algorithm}`,
  ]);

  const fingerprint = stdout
    .trim()
    .split("=")
    .at(1)
    ?.replaceAll(":", "")
    .trim();

  if (fingerprint) {
    return fingerprint;
  }

  throw new Error(
    `Could not determine ${algorithm} fingerprint for certificate at ${certificatePath}.`,
  );
}

function handleFatalError(error: unknown) {
  console.error(error);
  process.exitCode = 1;
}
